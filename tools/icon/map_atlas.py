import json
import os

from PIL import Image

import map_ground
import map_objects
from iso import render, to_image, transparent

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUTPUT = os.path.join(ROOT, 'images', 'iso')
MODULE = os.path.join(ROOT, 'src', 'isoArt.js')

GROUND_PER_ROW = 16
ATLAS_WIDTH = 1024


def draw_pair(builder):
    """An object's picture by day and its lights by night, cut to the same rectangle, and the pixel of its origin"""
    map_objects.STATE['lights'] = False
    shapes, sprites, lines, _ = builder()
    left, top, right, bottom = map_objects.extent(shapes, sprites, lines)
    width, height = right - left, bottom - top
    day = to_image(render(width, height, shapes, sprites, (-left, -top), transparent, lines))

    map_objects.STATE['lights'] = True
    try:
        shapes, _, _, _ = builder()
        night = to_image(render(width, height, shapes, [], (-left, -top), transparent, highlight=False,
                                outline=False))
    finally:
        map_objects.STATE['lights'] = False

    box = day.getbbox()
    return day.crop(box), night.crop(box), -left - box[0], -top - box[1], night.getbbox() is not None


def pack(pictures):
    """Places the pictures on shelves, tallest first: {name: (x, y)}, and the height of the atlas"""
    order = sorted(pictures, key=lambda name: (-pictures[name].height, name))
    at = {}
    x = y = shelf = 0
    for name in order:
        image = pictures[name]
        if x + image.width > ATLAS_WIDTH:
            x, y, shelf = 0, y + shelf + 1, 0
        at[name] = (x, y)
        x += image.width + 1
        shelf = max(shelf, image.height)
    return at, y + shelf


def ground():
    cells = map_ground.cells()
    rows = (len(cells) + GROUND_PER_ROW - 1) // GROUND_PER_ROW
    sheet = Image.new('RGBA', (GROUND_PER_ROW * map_ground.CELL_W, rows * map_ground.CELL_H), (0, 0, 0, 0))
    for index, (name, image) in enumerate(cells):
        sheet.paste(image, ((index % GROUND_PER_ROW) * map_ground.CELL_W, (index // GROUND_PER_ROW) * map_ground.CELL_H))
    sheet.save(os.path.join(OUTPUT, 'ground.png'), optimize=True)
    return [name for name, _ in cells]


def objects():
    days, nights, info = {}, {}, {}
    for name, size, builder in map_objects.objects():
        day, night, ax, ay, lit = draw_pair(builder)
        days[name], nights[name] = day, night
        info[name] = {'size': size, 'anchor': (ax, ay), 'lit': lit, 'emitters': map_objects.emitters(builder)}

    for name, builder in map_objects.vehicles():
        day, _, ax, ay, _ = draw_pair(builder)
        days[name] = day
        info[name] = {'size': 0, 'anchor': (ax, ay), 'lit': False, 'emitters': []}
        if name.startswith('plane') or name.startswith('copter'):
            shadow, _, sx, sy, _ = draw_pair(map_objects.shadow(builder))
            days[name + '_shadow'] = shadow
            info[name + '_shadow'] = {'size': 0, 'anchor': (sx, sy), 'lit': False, 'emitters': []}

    at, height = pack(days)
    day_sheet = Image.new('RGBA', (ATLAS_WIDTH, height), (0, 0, 0, 0))
    night_sheet = Image.new('RGBA', (ATLAS_WIDTH, height), (0, 0, 0, 0))
    for name, image in days.items():
        day_sheet.paste(image, at[name])
        if info[name]['lit']:
            night_sheet.paste(nights[name], at[name])
    day_sheet.save(os.path.join(OUTPUT, 'objects.png'), optimize=True)
    night_sheet.save(os.path.join(OUTPUT, 'lights.png'), optimize=True)

    table = {}
    for name in sorted(days):
        x, y = at[name]
        entry = [x, y, days[name].width, days[name].height, info[name]['anchor'][0], info[name]['anchor'][1],
                 info[name]['size'], 1 if info[name]['lit'] else 0]
        table[name] = entry
    emitters = {name: [[round(v, 1) if isinstance(v, float) else v for v in e] for e in info[name]['emitters']]
                for name in sorted(info) if info[name]['emitters']}
    return table, emitters, (ATLAS_WIDTH, height)


def main():
    os.makedirs(OUTPUT, exist_ok=True)
    cells = ground()
    table, emitters, size = objects()

    with open(MODULE, 'w') as out:
        out.write('// Generated by tools/icon/map_atlas.py: do not edit.\n//\n')
        out.write('// The art of the isometric map, in images/iso. GROUND_CELLS names the cells of ground.png, laid out\n')
        out.write('// GROUND_PER_ROW to a row, each CELL_W x CELL_H pixels, the top corner of the tile at (17, 1).\n')
        out.write('// OBJECTS gives, for each picture of objects.png (and of lights.png, laid out the same, when it is lit\n')
        out.write('// by night): [x, y, width, height, x of its origin, y of its origin, size in tiles, lit]. EMITTERS\n')
        out.write('// gives where smoke or steam rises from a building: [X, Y, Z, kind], from its origin.\n\n')
        out.write('var CELL_W = %d;\nvar CELL_H = %d;\nvar GROUND_PER_ROW = %d;\n\n' %
                  (map_ground.CELL_W, map_ground.CELL_H, GROUND_PER_ROW))
        out.write('var GROUND_CELLS = %s;\n\n' % json.dumps(cells))
        out.write('var OBJECTS = {\n')
        out.write(',\n'.join('  %s: %s' % (json.dumps(name), json.dumps(entry)) for name, entry in table.items()))
        out.write('\n};\n\n')
        out.write('var EMITTERS = %s;\n\n' % json.dumps(emitters))
        out.write('var ATLAS_SIZE = %s;\n\n\n' % json.dumps(list(size)))
        out.write('export { ATLAS_SIZE, CELL_H, CELL_W, EMITTERS, GROUND_CELLS, GROUND_PER_ROW, OBJECTS };\n')

    print('Map art written to', os.path.relpath(OUTPUT, ROOT), 'and', os.path.relpath(MODULE, ROOT), '(atlas %dx%d)'
          % size)


if __name__ == '__main__':
    main()
